export function toPlayerUrl(url, params = 'background=1&autoplay=1&muted=1&loop=1') {
  if (!url) return undefined;
  const hMatch = url.match(/[?&]h=([a-f0-9]+)/);
  const hParam = hMatch ? `&h=${hMatch[1]}` : '';
  if (url.includes('player.vimeo.com')) {
    return `${url.split('?')[0]}?${params}${hParam}`;
  }
  const match = url.match(/vimeo\.com\/(?:video\/)?(\d+)/);
  if (match) return `https://player.vimeo.com/video/${match[1]}?${params}${hParam}`;
  if (/^\d+$/.test(url.trim())) return `https://player.vimeo.com/video/${url.trim()}?${params}`;
  return undefined;
}


